CREATE TABLE IF NOT EXISTS building_reports (
  report_id VARCHAR(64) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  input_hash CHAR(64) NOT NULL,
  protocol_version VARCHAR(64) NOT NULL,
  input_json JSON NOT NULL,
  preview_snapshot JSON NULL,
  full_snapshot JSON NULL,
  status VARCHAR(32) NOT NULL,
  generation_mode VARCHAR(32) NOT NULL DEFAULT 'rules_only',
  paid TINYINT(1) NOT NULL DEFAULT 0,
  bound TINYINT(1) NOT NULL DEFAULT 0,
  payment_ref VARCHAR(128) NULL,
  pending_order_no VARCHAR(128) NULL,
  reserved_product_id VARCHAR(64) NULL,
  reserved_price_fen BIGINT NULL,
  reserved_pack_id VARCHAR(64) NULL,
  reserved_pack_version VARCHAR(64) NULL,
  external_user_id VARCHAR(128) NULL,
  pack_id VARCHAR(64) NULL,
  pack_version VARCHAR(64) NULL,
  preview_object_key VARCHAR(512) NULL,
  full_object_key VARCHAR(512) NULL,
  attempt_count INT NOT NULL DEFAULT 0,
  failed_stage VARCHAR(16) NULL,
  error_code VARCHAR(64) NULL,
  lease_token VARCHAR(64) NULL,
  lease_until DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (report_id),
  UNIQUE KEY uk_report_user_input_protocol (user_id, input_hash, protocol_version),
  UNIQUE KEY uk_report_pending_order (pending_order_no),
  UNIQUE KEY uk_report_payment_ref (payment_ref),
  KEY idx_report_user_created (user_id, created_at),
  KEY idx_report_claim (status, lease_until, attempt_count, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='建房规划报告状态、冻结快照与私有文档索引';
